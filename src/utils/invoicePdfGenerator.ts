/** Format numeric cell for display: use data when present, otherwise 0.00 for price-like fields. */
function formatInvoiceCellValue(key: string, v: unknown): string {
  const num = v !== null && v !== undefined ? Number(v) : NaN;
  if (key === 'orderQty' || key === 'shippedQty') {
    return Number.isNaN(num) ? '0' : String(Math.round(num));
  }
  if (['price', 'unitPrice', 'tax', 'prepaidTaxAmount', 'totalPPD', 'priceWithTaxWithPPD', 'priceWithTaxWithoutPPD', 'extendedTotal', 'totalPrice', 'retail1', 'deposit'].includes(key)) {
    return Number.isNaN(num) ? '0.00' : Number(num).toFixed(2);
  }
  if (v === null || v === undefined) return '';
  return String(v);
}

/** Build one group-subtotal row: Price, EXT Price with/without PPD, extended total, totalPPD sums; per-unit columns blank. */
function buildGroupSubtotalRow(
  selectedKeys: string[],
  groupLabel: string,
  items: InvoiceLineItem[],
  template: InvoiceTemplateConfig
): string[] {
  const orderQtySum = items.reduce((s, i) => s + (Number(i.orderQty) || 0), 0);
  const shippedQtySum = items.reduce((s, i) => s + (Number(i.shippedQty) || 0), 0);
  const useWithoutPPD = template.extendedTotalBasedOn === 'withoutPPD';
  const extendedTotalSum = items.reduce((s, i) => {
    const qty = Number(i.shippedQty) || 0;
    const ext = useWithoutPPD
      ? (i.priceWithTaxWithoutPPD ?? (i.priceWithTax - (i.prepaidTaxAmount ?? 0))) * qty
      : (Number(i.totalPrice) || 0);
    return s + ext;
  }, 0);
  const totalPPDSum = items.reduce((s, i) => s + (Number(i.prepaidTaxAmount ?? 0) * (Number(i.shippedQty) || 0)), 0);
  const priceSum = items.reduce((s, i) => s + (Number(i.price) || 0) * (Number(i.shippedQty) || 0), 0);
  const priceWithPPDSum = items.reduce((s, i) => {
    const qty = Number(i.shippedQty) || 0;
    return s + (i.priceWithTaxWithPPD ?? i.priceWithTax ?? 0) * qty;
  }, 0);
  const priceWithoutPPDSum = items.reduce((s, i) => {
    const qty = Number(i.shippedQty) || 0;
    return s + (i.priceWithTaxWithoutPPD ?? (i.priceWithTax - (i.prepaidTaxAmount ?? 0))) * qty;
  }, 0);
  return selectedKeys.map((key) => {
    if (key === 'description') return groupLabel;
    if (key === 'orderQty') return String(Math.round(orderQtySum));
    if (key === 'shippedQty') return String(Math.round(shippedQtySum));
    if (key === 'price') return priceSum.toFixed(2);
    if (key === 'priceWithTaxWithPPD') return priceWithPPDSum.toFixed(2);
    if (key === 'priceWithTaxWithoutPPD') return priceWithoutPPDSum.toFixed(2);
    if (key === 'extendedTotal') return extendedTotalSum.toFixed(2);
    if (key === 'totalPPD') return totalPPDSum.toFixed(2);
    if (key === 'prepaidTaxAmount' || key === 'unitPrice') return '';
    if (key === 'pack' || key === 'size' || key === 'deposit' || key === 'ebt') return '';
    return '';
  });
}

/** Compute sales category summary: category -> { qty, extended }. EXTEN uses same basis as extended total (EXT Price with PPD or without PPD). */
function getCategorySummary(
  items: InvoiceLineItem[],
  extendedTotalBasedOn?: string
): Array<{ category: string; qty: number; extended: number }> {
  const useWithoutPPD = extendedTotalBasedOn === 'withoutPPD';
  const map: Record<string, { qty: number; extended: number }> = {};
  items.forEach((item) => {
    const cat = item.salesCategory || 'Other';
    if (!map[cat]) map[cat] = { qty: 0, extended: 0 };
    const qty = Number(item.shippedQty) || Number(item.orderQty) || 0;
    map[cat].qty += qty;
    const ext = useWithoutPPD
      ? (item.priceWithTaxWithoutPPD ?? (item.priceWithTax - (item.prepaidTaxAmount ?? 0))) * qty
      : Number(item.totalPrice) || 0;
    map[cat].extended += ext;
  });
  return Object.keys(map)
    .sort()
    .map((category) => ({ category, qty: map[category].qty, extended: map[category].extended }));
}

/**
 * Generate invoice PDF using order data and template config (same layout/conditions as InvoiceTemplateTab preview).
 * Distributor details and logo are loaded from Contact Us when available.
 * When options.print is true, opens print dialog instead of downloading.
 */
export async function generateInvoicePDF(
  orderData: InvoiceOrderData,
  template: InvoiceTemplateConfig,
  options?: GenerateInvoicePDFOptions
): Promise<void> {
  let contactData: ContactUsData | null = null;
  try {
    const data = await getContactUsData();
    contactData = Array.isArray(data) ? (data[0] as ContactUsData) ?? null : (data as ContactUsData) ?? null;
  } catch {
    // use orderData.distributor and default logo
  }
  const distributorFromContact =
    contactData &&
    (contactData.D_Name || contactData.D_Addr1 || contactData.D_City || contactData.D_State || contactData.D_Zip)
      ? {
          name: contactData.D_Name ?? orderData.distributor.name,
          address:
            [contactData.D_Addr1, contactData.D_City, contactData.D_State, contactData.D_Zip]
              .filter(Boolean)
              .join(', ') || (orderData.distributor.address ?? ''),
          orderLine: contactData.D_OrderLine ?? orderData.distributor.orderLine,
          phoneFax: contactData.D_Phone ?? orderData.distributor.phoneFax,
          whatsapp: contactData.D_Whatsapp ?? orderData.distributor.whatsapp,
        }
      : null;
  const pdfOrderData: InvoiceOrderData = distributorFromContact
    ? { ...orderData, distributor: distributorFromContact }
    : orderData;
  // Warehouse logo for header: optional explicit URL first, then Contact Us (logo or D_Logo).
  const warehouseLogoUrl = options?.warehouseLogoUrl || contactData?.logo || contactData?.D_Logo;
  const logoFromContact = warehouseLogoUrl ? await loadLogoFromUrl(warehouseLogoUrl) : null;
  // "Report generated by Woopsa" footer always uses Rabbit logo only (not warehouse logo).
  const footerLogo = await loadRabbitLogoAsDataUrl();
  let selectedKeys = getOrderedSelectedKeys(template);
  // PDF only: show EBT column only if at least one item has ebt true; when shown, header is empty (no "EBT" label)
  if (selectedKeys.includes('ebt')) {
    const hasAnyEbt = pdfOrderData.items.some((item) => item.ebt === true);
    if (!hasAnyEbt) selectedKeys = selectedKeys.filter((k) => k !== 'ebt');
  }
  const upcColIndex = selectedKeys.indexOf('upc');
  const descriptionColIndex = selectedKeys.indexOf('description');
  const showUpcAsBarcode = template.upcOption.startsWith('barcode');
  const columnStyles: Record<number, { cellWidth: number }> = {};
  if (descriptionColIndex >= 0) {
    columnStyles[descriptionColIndex] = { cellWidth: DESCRIPTION_COLUMN_WIDTH_MM };
  }
  const doc = new jsPDF('landscape', 'mm', 'a4');
  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 10;
  const headerHeight = addInvoiceHeaderToPage(doc, pdfOrderData, template, 1, 1, logoFromContact);
  const tableMarginTopNewPages =
    template.headerOnPages === 'all'
      ? headerHeight
      : template.headerOnPages === 'firstPlusSummary'
        ? SUMMARY_HEADER_HEIGHT_MM
        : margin;
  let yPos = headerHeight + 2;
  const grouped = groupInvoiceItems(template, pdfOrderData.items);
  // EBT column: no table header (empty label) when shown. Use columnHeaderNames from template when set.
  const headerLabels = selectedKeys.map((k) => {
    const custom = template.columnHeaderNames?.[k]?.trim();
    if (custom) return custom;
    return k === 'ebt' ? '' : (INVOICE_COLUMN_FIELDS.find((f) => f.key === k)?.label || k);
  });
  const autoTableFn = jspdfAutoTable.default || jspdfAutoTable.autoTable || jspdfAutoTable;
  const tableBottomMarginMM = getTableBottomMarginMM(template);
  const totalPagesEstimate = estimateTotalPages(
    grouped,
    template,
    headerHeight,
    tableMarginTopNewPages,
    pageHeight,
    tableBottomMarginMM
  );

  const itemsTableWidth = pageWidth - margin * 2;
  const showGroupSubtotal =
    template.groupBy === 'alphabetSalesCategory' || template.groupBy === 'sequence';

  const getMinYBeforeFooter = (): number => {
    const currentPage = doc.getNumberOfPages();
    const marginBottom = currentPage === totalPagesEstimate ? tableBottomMarginMM : NON_LAST_PAGE_BOTTOM_MM;
    return pageHeight - marginBottom;
  };

  grouped.forEach((group, groupIdx) => {
    if (groupIdx > 0) yPos += 4;
    let minYBeforeFooter = getMinYBeforeFooter();
    if (template.groupBy === 'alphabetSalesCategory' && template.showGroupHeader && group.label != null) {
      if (yPos > minYBeforeFooter) {
        doc.addPage('a4', 'landscape');
        const currentP = doc.getNumberOfPages();
        if (template.headerOnPages === 'all') {
          yPos = addInvoiceHeaderToPage(doc, pdfOrderData, template, currentP, totalPagesEstimate, logoFromContact) + 2;
        } else if (template.headerOnPages === 'firstPlusSummary') {
          yPos = addInvoiceSummaryHeaderToPage(doc, pdfOrderData, template, currentP, totalPagesEstimate, logoFromContact) + 2;
        } else {
          yPos = tableMarginTopNewPages + 2;
        }
        minYBeforeFooter = getMinYBeforeFooter();
      }
      doc.setFillColor(240, 245, 250);
      doc.roundedRect(margin, yPos - 3, pageWidth - margin * 2, 6, 1, 1, 'FD');
      doc.setFontSize(9);
      doc.setFont('helvetica', 'normal');
      doc.text(`Sales Category: ${group.label}`, margin + 3, yPos + 1);
      yPos += 8;
    }
    if (template.groupBy === 'sequence' && template.showGroupHeader && group.key) {
      minYBeforeFooter = getMinYBeforeFooter();
      if (yPos > minYBeforeFooter) {
        doc.addPage('a4', 'landscape');
        const currentP = doc.getNumberOfPages();
        if (template.headerOnPages === 'all') {
          yPos = addInvoiceHeaderToPage(doc, pdfOrderData, template, currentP, totalPagesEstimate, logoFromContact) + 2;
        } else if (template.headerOnPages === 'firstPlusSummary') {
          yPos = addInvoiceSummaryHeaderToPage(doc, pdfOrderData, template, currentP, totalPagesEstimate, logoFromContact) + 2;
        } else {
          yPos = tableMarginTopNewPages + 2;
        }
        minYBeforeFooter = getMinYBeforeFooter();
      }
      doc.setFillColor(240, 245, 250);
      doc.roundedRect(margin, yPos - 3, pageWidth - margin * 2, 6, 1, 1, 'FD');
      doc.setFontSize(9);
      doc.setFont('helvetica', 'normal');
      doc.text(`Sequence: ${group.key}`, margin + 3, yPos + 1);
      yPos += 8;
    }
    minYBeforeFooter = getMinYBeforeFooter();
    if (yPos > minYBeforeFooter) {
      doc.addPage('a4', 'landscape');
      const currentP = doc.getNumberOfPages();
      if (template.headerOnPages === 'all') {
        yPos = addInvoiceHeaderToPage(doc, pdfOrderData, template, currentP, totalPagesEstimate, logoFromContact) + 2;
      } else if (template.headerOnPages === 'firstPlusSummary') {
        yPos = addInvoiceSummaryHeaderToPage(doc, pdfOrderData, template, currentP, totalPagesEstimate, logoFromContact) + 2;
      } else {
        yPos = tableMarginTopNewPages + 2;
      }
      minYBeforeFooter = getMinYBeforeFooter();
    }
    const currentPageForMargin = doc.getNumberOfPages();
    const marginBottomThisPage =
      currentPageForMargin === totalPagesEstimate ? tableBottomMarginMM : NON_LAST_PAGE_BOTTOM_MM;
    doc.setFontSize(7);
    const descColWidthMm = DESCRIPTION_COLUMN_WIDTH_MM - 3;
    const itemRows = group.items.map((item) =>
      selectedKeys.map((key) => {
        if (key === 'ebt') return item.ebt ? 'E' : '';
        if (key === 'upc' && showUpcAsBarcode) return '';
        if (key === 'description') {
          const descLines = wrapFooterMessage(doc, item.description || '', descColWidthMm, 15);
          return descLines.join('\n') + (item.outOfStockNote ? '\n*This item was out of stock' : '');
        }
        let v: unknown = (item as unknown as Record<string, unknown>)[key];
        if (v === undefined || v === null) {
          if (key === 'priceWithTaxWithPPD') v = item.priceWithTax;
          else if (key === 'priceWithTaxWithoutPPD') v = item.priceWithTaxWithoutPPD ?? (item.priceWithTax - (item.prepaidTaxAmount ?? 0));
          else if (key === 'unitPrice') v = item.unitPrice ?? item.price;
          else if (key === 'prepaidTaxAmount') v = item.prepaidTaxAmount;
          else if (key === 'totalPPD') v = (item.prepaidTaxAmount ?? 0) * (item.shippedQty || 0);
          else if (key === 'extendedTotal') {
            const useWithoutPPD = template.extendedTotalBasedOn === 'withoutPPD';
            const qty = item.shippedQty || 0;
            v = useWithoutPPD
              ? (item.priceWithTaxWithoutPPD ?? (item.priceWithTax - (item.prepaidTaxAmount ?? 0))) * qty
              : (item.totalPrice ?? 0);
          }
        }
        return formatInvoiceCellValue(key, v);
      })
    );
    const body: string[][] = [...itemRows];
    if (showGroupSubtotal && (template.groupBy === 'alphabetSalesCategory' || template.groupBy === 'sequence')) {
      const groupLabel =
        template.groupBy === 'alphabetSalesCategory' ? (group.label ?? group.key) : `Sequence: ${group.key}`;
      body.push(buildGroupSubtotalRow(selectedKeys, groupLabel, group.items, template));
    }
    const currentGroupItems = group.items;
    const subtotalRowIndex = body.length - 1;
    const hasSubtotalRow = showGroupSubtotal && (template.groupBy === 'alphabetSalesCategory' || template.groupBy === 'sequence') && body.length > group.items.length;
    const rowStyles: Record<number, { fillColor: number[] }> = {};
    body.forEach((_, i) => {
      rowStyles[i] = i === subtotalRowIndex && hasSubtotalRow
        ? { fillColor: [220, 220, 220] }
        : { fillColor: i % 2 === 0 ? [248, 248, 248] : [255, 255, 255] };
    });
    autoTableFn(doc, {
      head: [headerLabels],
      body,
      startY: yPos,
      tableWidth: itemsTableWidth,
      styles: { fontSize: 7, cellPadding: 1.5 },
      headStyles: { fillColor: [240, 240, 240], fontSize: 7, textColor: [0, 0, 0], fontStyle: 'normal' },
      columnStyles: Object.keys(columnStyles).length > 0 ? columnStyles : undefined,
      rowStyles: Object.keys(rowStyles).length > 0 ? rowStyles : undefined,
      margin: {
        left: margin,
        right: margin,
        top: tableMarginTopNewPages,
        bottom: marginBottomThisPage,
      },
      didDrawCell: (data: { section: string; row: { index: number }; column: { index: number }; cell: { x: number; y: number; width: number; height: number } }) => {
        if (data.section !== 'body' || data.row.index >= currentGroupItems.length) return;
        const item = currentGroupItems[data.row.index];
        if (upcColIndex >= 0 && data.column.index === upcColIndex && showUpcAsBarcode) {
          const upc = item?.upc;
          if (upc) {
            const barcodeDataUrl = generateBarcodeDataUrl(upc);
            if (barcodeDataUrl) {
              try {
                const w = Math.min(data.cell.width - 1, 38);
                const h = Math.min(data.cell.height - 1, 18);
                doc.addImage(barcodeDataUrl, 'PNG', data.cell.x + 0.5, data.cell.y + 0.5, w, h);
              } catch {
                doc.setFontSize(6);
                doc.text(upc, data.cell.x + 1, data.cell.y + data.cell.height / 2 + 1);
              }
            }
          }
          return;
        }
        if (descriptionColIndex >= 0 && data.column.index === descriptionColIndex && item?.outOfStockNote) {
          const rowFill = data.row.index % 2 === 0 ? [248, 248, 248] : [255, 255, 255];
          doc.setFillColor(rowFill[0], rowFill[1], rowFill[2]);
          doc.rect(data.cell.x, data.cell.y, data.cell.width, data.cell.height, 'F');
          doc.setFont('helvetica', 'normal');
          doc.setTextColor(0, 0, 0);
          const cellPad = 1.5;
          const lineHeightMm = 3.5;
          doc.setFontSize(7);
          const descLines = wrapFooterMessage(doc, item.description || '', data.cell.width - cellPad * 2, 15);
          descLines.forEach((line, i) => {
            doc.setFontSize(7);
            doc.text(line, data.cell.x + cellPad, data.cell.y + 4 + i * lineHeightMm);
          });
          doc.setFontSize(5);
          doc.text('*This item was out of stock', data.cell.x + cellPad, data.cell.y + 4 + descLines.length * lineHeightMm);
        }
      },
    });
    yPos = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 2;
  });

  let categoryTableBottomY: number | undefined;
  const pagesBeforeCategory = doc.getNumberOfPages();
  if (pagesBeforeCategory > 0) {
    doc.setPage(pagesBeforeCategory);
    const lastPageY = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? yPos;
    const categorySummary = getCategorySummary(pdfOrderData.items, template.extendedTotalBasedOn);
    const totalQty = categorySummary.reduce((s, c) => s + c.qty, 0);
    const totalExtended = categorySummary.reduce((s, c) => s + c.extended, 0);
    if (categorySummary.length > 0) {
      // Reserve space above footer: content must end above this Y to avoid overlap with footer
      const footerZoneTopY = pageHeight - WOOPSA_LINE_BOTTOM_MM - 1 - LAST_PAGE_FOOTER_BLOCK_MM - GAP_CATEGORY_TO_FOOTER_MM;
      const categoryRows = categorySummary.length + 1; // +1 for TOTAL row
      const estimatedCategoryTableHeight = 6 + categoryRows * CATEGORY_TABLE_ROW_HEIGHT_MM; // header + rows
      const categoryStartY = lastPageY + 6;
      const wouldOverlapFooter = categoryStartY + estimatedCategoryTableHeight > footerZoneTopY;

      let startY: number;
      if (wouldOverlapFooter) {
        doc.addPage('a4', 'landscape');
        const newPageNum = doc.getNumberOfPages();
        if (template.headerOnPages === 'all') {
          startY = addInvoiceHeaderToPage(doc, pdfOrderData, template, newPageNum, newPageNum, logoFromContact) + 2;
        } else if (template.headerOnPages === 'firstPlusSummary') {
          startY = addInvoiceSummaryHeaderToPage(doc, pdfOrderData, template, newPageNum, newPageNum, logoFromContact) + 2;
        } else {
          startY = tableMarginTopNewPages + 2;
        }
      } else {
        startY = categoryStartY;
      }

      const categoryTableWidth = Math.min(itemsTableWidth, 120);
      const catCol1 = categoryTableWidth * 0.6;
      const catCol2 = categoryTableWidth * 0.2;
      const catCol3 = categoryTableWidth * 0.2;
      const categoryHead = [['QTY CATEGORY', 'QTY', 'EXTEN']];
      const categoryBody = categorySummary.map(({ category, qty, extended }) => [
        category,
        qty.toFixed(2),
        formatCurrency(extended),
      ]);
      categoryBody.push(['TOTAL', totalQty.toFixed(2), formatCurrency(totalExtended)]);
      autoTableFn(doc, {
        startY,
        head: categoryHead,
        body: categoryBody,
        columnStyles: { 0: { cellWidth: catCol1 }, 1: { cellWidth: catCol2 }, 2: { cellWidth: catCol3 } },
        styles: { fontSize: 7, cellPadding: 2 },
        headStyles: { fillColor: [220, 220, 220], fontSize: 7, textColor: [0, 0, 0], fontStyle: 'normal' },
        margin: { left: margin, right: margin },
        tableWidth: categoryTableWidth,
      });
      categoryTableBottomY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY;
    }
  }
  // Use page count after category table (it may have added a page if table didn't fit)
  const totalPages = doc.getNumberOfPages();
  for (let i = 1; i <= totalPages; i++) {
    doc.setPage(i);
    addInvoiceFooterToPage(
      doc,
      pdfOrderData,
      template,
      footerLogo,
      i === totalPages,
      i === totalPages ? categoryTableBottomY : undefined
    );
    if (template.headerOnPages === 'first' && i > 1) {
      // no header on 2nd+ pages (same as InvoiceTemplateTab)
    } else if (template.headerOnPages === 'firstPlusSummary' && i > 1) {
      addInvoiceSummaryHeaderToPage(doc, pdfOrderData, template, i, totalPages, logoFromContact);
    } else {
      addInvoiceHeaderToPage(doc, pdfOrderData, template, i, totalPages, logoFromContact);
    }
  }

  if (options?.print) {
    try {
      doc.autoPrint();
      const blob = doc.output('blob');
      const url = URL.createObjectURL(blob);
      const printWindow = window.open(url, '_blank');
      if (printWindow) {
        printWindow.onload = () => printWindow.print();
        setTimeout(() => {
          try {
            printWindow.print();
          } catch {
            // ignore
          }
          URL.revokeObjectURL(url);
        }, 800);
      } else {
        URL.revokeObjectURL(url);
        const timestamp = new Date().toISOString().split('T')[0];
        doc.save(`invoice-${orderData.orderNumber}-${timestamp}.pdf`);
      }
    } catch {
      const timestamp = new Date().toISOString().split('T')[0];
      doc.save(`invoice-${orderData.orderNumber}-${timestamp}.pdf`);
    }
  } else {
    const timestamp = new Date().toISOString().split('T')[0];
    doc.save(`invoice-${orderData.orderNumber}-${timestamp}.pdf`);
  }
}
