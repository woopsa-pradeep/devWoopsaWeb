const generateBarcodeDataUrl = (text: string): string | null => {
  try {
    const canvas = document.createElement('canvas');
    JsBarcode(canvas, text, { format: 'CODE128', width: 2, height: 40, displayValue: false, margin: 2 });
    return canvas.toDataURL('image/png');
  } catch {
    return null;
  }
};

/** Load image from URL and return as data URL (for Contact Us logo). */
const loadLogoFromUrl = (url: string): Promise<string | null> => {
  return new Promise<string | null>((resolve) => {
    const img = new Image();
    img.crossOrigin = 'anonymous';
    img.onload = () => {
      try {
        const canvas = document.createElement('canvas');
        const ctx = canvas.getContext('2d');
        if (ctx) {
          canvas.width = img.width || 40;
          canvas.height = img.height || 33;
          ctx.drawImage(img, 0, 0);
          resolve(canvas.toDataURL('image/png'));
        } else resolve(null);
      } catch {
        resolve(null);
      }
    };
    img.onerror = () => resolve(null);
    img.src = url;
  });
};

/** Load Woopsa Rabbit logo as data URL for "Report generated by Woopsa" footer. */
const loadRabbitLogoAsDataUrl = async (): Promise<string | null> => {
  const logoPath = typeof rabbitLogo === 'string' ? rabbitLogo : (rabbitLogo as string);
  try {
    const dataUrl = await loadLogoFromUrl(logoPath);
    if (dataUrl) return dataUrl;
    const fetchUrl = logoPath.startsWith('data:') || logoPath.startsWith('http') ? logoPath : (logoPath.startsWith('/') ? logoPath : `/${logoPath}`);
    const response = await fetch(fetchUrl);
    if (!response.ok) return null;
    const blob = await response.blob();
    return new Promise<string | null>((resolve) => {
      const reader = new FileReader();
      reader.onloadend = () => resolve(typeof reader.result === 'string' ? reader.result : null);
      reader.onerror = () => resolve(null);
      reader.readAsDataURL(blob);
    });
  } catch {
    return null;
  }
};

const formatCurrency = (n: number): string => (n != null && !Number.isNaN(n) ? `$${Number(n).toFixed(2)}` : '$0.00');

/** Format date string (ISO or YYYY-MM-DD) to MM/DD/YYYY for display. */
const formatInvoiceDate = (dateStr: string): string => {
  if (!dateStr || typeof dateStr !== 'string') return '';
  const trimmed = dateStr.trim().split('T')[0];
  const match = trimmed.match(/^(\d{4})-(\d{2})-(\d{2})/);
  if (match) return `${match[2]}/${match[3]}/${match[1]}`;
  return dateStr;
};

const descriptionSortOrder = (a: string, b: string): number => {
  const cat = (ch: string): number => {
    if (ch === ' ' || ch === '') return 0;
    if (/[0-9]/.test(ch)) return 2;
    if (/[A-Za-z]/.test(ch)) return 3;
    return 1;
  };
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    const ca = a[i] ?? '';
    const cb = b[i] ?? '';
    const diff = cat(ca) - cat(cb);
    if (diff !== 0) return diff;
    if (ca !== cb) return ca.localeCompare(cb, undefined, { numeric: true });
  }
  return 0;
};

function groupInvoiceItems(
  template: InvoiceTemplateConfig,
  items: InvoiceLineItem[]
): Array<{ key: string; label?: string; items: InvoiceLineItem[] }> {
  const groupBy = template.groupBy;
  const showGroupHeader = template.showGroupHeader;
  if (!groupBy) return [{ key: 'all', items: [...items].sort((a, b) => a.sortNumber - b.sortNumber) }];
  if (groupBy === 'sequence') {
    const map: Record<string, InvoiceLineItem[]> = {};
    items.forEach((item) => {
      const k = String(item.sortNumber);
      if (!map[k]) map[k] = [];
      map[k].push(item);
    });
    return Object.keys(map)
      .sort((a, b) => Number(a) - Number(b))
      .map((key) => ({ key, items: map[key] }));
  }
  if (groupBy === 'alphabet') {
    const sorted = [...items].sort((a, b) =>
      descriptionSortOrder((a.description || '').trim(), (b.description || '').trim())
    );
    return [{ key: 'all', items: sorted }];
  }
  if (groupBy === 'alphabetSalesCategory') {
    const byCat: Record<string, InvoiceLineItem[]> = {};
    items.forEach((item) => {
      const cat = item.salesCategory || 'Other';
      if (!byCat[cat]) byCat[cat] = [];
      byCat[cat].push(item);
    });
    const result: Array<{ key: string; label?: string; items: InvoiceLineItem[] }> = [];
    Object.keys(byCat)
      .sort()
      .forEach((cat) => {
        const list = byCat[cat].sort((a, b) =>
          descriptionSortOrder((a.description || '').trim(), (b.description || '').trim())
        );
        if (showGroupHeader) result.push({ key: cat, label: cat, items: list });
        else result.push({ key: cat, items: list });
      });
    return result;
  }
  return [{ key: 'all', items: [...items].sort((a, b) => a.sortNumber - b.sortNumber) }];
}

/** Draw header tables on the right: 3 rows only (reduced size). Returns bottom Y. */
function drawHeaderTables(
  doc: jsPDF,
  orderData: InvoiceOrderData,
  template: InvoiceTemplateConfig,
  startX: number,
  startY: number,
  tableWidth: number,
  pageWidth: number,
  pageMargin: number
): number {
  const cust = orderData.customer;
  const formatDate = (): string => formatInvoiceDate(orderData.invoiceDate || orderData.orderDate || '');
  const autoTableFn = jspdfAutoTable.default || jspdfAutoTable.autoTable || jspdfAutoTable;
  const greyHead = { fillColor: [200, 200, 200] as [number, number, number], textColor: [0, 0, 0], fontStyle: 'normal', fontSize: 5 };
  const cellW3 = tableWidth / 3;
  const tableMargin = { left: startX, right: pageMargin };
  const tableStyle = { fontSize: 5, cellPadding: 1 };

  // Row 1: CUSTOMER NO | INVOICE# | INVOICE DATE
  autoTableFn(doc, {
    startY,
    head: [['CUSTOMER NO', 'INVOICE#:', 'INVOICE DATE:']],
    body: [[String(cust.number), orderData.invoiceNumber, formatDate()]],
    columnStyles: { 0: { cellWidth: cellW3 }, 1: { cellWidth: cellW3 }, 2: { cellWidth: cellW3 } },
    styles: tableStyle,
    headStyles: greyHead,
    margin: tableMargin,
    tableWidth,
  });
  let y = (doc as any).lastAutoTable.finalY + 0.5;

  // Row 2: TERMS | CUSTOMER LICENCE# | Delivery Via (from orderData.via = Delivery_Description when present)
  const termsText = orderData.termsCode != null ? String(orderData.termsCode) : '';
  const licenseText = (orderData.customerLicense ?? '').trim() ? orderData.customerLicense! : '-';
  const viaText = (orderData.via ?? '').trim() || '-';
  autoTableFn(doc, {
    startY: y,
    head: [['TERMS:', 'CUSTOMER LICENCE#', 'Delivery Via']],
    body: [[termsText || '-', `${licenseText}`, viaText]],
    columnStyles: { 0: { cellWidth: cellW3 }, 1: { cellWidth: cellW3 }, 2: { cellWidth: cellW3 } },
    styles: tableStyle,
    headStyles: greyHead,
    margin: tableMargin,
    tableWidth,
  });
  y = (doc as any).lastAutoTable.finalY + 0.5;

  // Row 3: SALES PERSON | ROUTE NUMBER | STOP NUMBER (from orderData when present)
  const salesPersonText = (orderData.salesPerson ?? '').trim() || '-';
  const routeText = template.showRoute ? String(cust.route ?? '') : '';
  const stopText = template.showStop ? String(cust.stop ?? '') : '';
  autoTableFn(doc, {
    startY: y,
    head: [['SALES PERSON', 'ROUTE NUMBER', 'STOP NUMBER']],
    body: [[salesPersonText, routeText, stopText]],
    columnStyles: { 0: { cellWidth: cellW3 }, 1: { cellWidth: cellW3 }, 2: { cellWidth: cellW3 } },
    styles: tableStyle,
    headStyles: greyHead,
    margin: tableMargin,
    tableWidth,
  });
  return (doc as any).lastAutoTable.finalY;
}

const BILL_SHIP_HEADER_COLOR = [70, 70, 90] as [number, number, number];

/** Draw BILL TO / SHIP TO as one table. Bill To uses orderData.billTo when present, else customer (same as Ship To). Returns bottom Y. */
function drawBillToShipTo(
  doc: jsPDF,
  orderData: InvoiceOrderData,
  template: InvoiceTemplateConfig,
  startY: number,
  leftX: number,
  pageWidth: number,
  margin: number
): number {
  if (!template.showCustomerDetails || (!template.showBillTo && !template.showShipTo)) return startY;
  const cust = orderData.customer;
  const shipToLines: string[] = [cust.name || ''];
  const shipAddr = (cust.address || '').trim();
  if (shipAddr) shipAddr.split(',').map((p) => p.trim()).filter(Boolean).forEach((p) => shipToLines.push(p));
  if (cust.phone) shipToLines.push(`PHONE: ${cust.phone}`);
  const shipToContent = shipToLines.join('\n');
  const billToSource = orderData.billTo ?? cust;
  const billToLines: string[] = [billToSource.name || ''];
  const billAddr = (billToSource.address || '').trim();
  if (billAddr) billAddr.split(',').map((p) => p.trim()).filter(Boolean).forEach((p) => billToLines.push(p));
  if (billToSource.phone) billToLines.push(`PHONE: ${billToSource.phone}`);
  const billToContent = billToLines.join('\n');
  const tableWidth = pageWidth - margin * 2;
  const headCols: string[] = [];
  const bodyCols: string[] = [];
  if (template.showBillTo) {
    headCols.push('BILL TO');
    bodyCols.push(billToContent);
  }
  if (template.showShipTo) {
    headCols.push('SHIP TO');
    bodyCols.push(shipToContent);
  }
  const colCount = headCols.length;
  const colWidth = tableWidth / colCount;
  const columnStyles: Record<number, { cellWidth: number }> = {};
  for (let i = 0; i < colCount; i++) columnStyles[i] = { cellWidth: colWidth };
  const autoTableFn = jspdfAutoTable.default || jspdfAutoTable.autoTable || jspdfAutoTable;
  autoTableFn(doc, {
    startY,
    head: [headCols],
    body: [bodyCols],
    columnStyles,
    styles: { fontSize: 6, cellPadding: 2 },
    headStyles: {
      fillColor: BILL_SHIP_HEADER_COLOR,
      textColor: [255, 255, 255],
      fontStyle: 'normal',
      fontSize: 6,
    },
    margin: { left: leftX, right: margin },
    tableWidth,
  });
  return (doc as any).lastAutoTable.finalY;
}

function addInvoiceHeaderToPage(
  doc: jsPDF,
  orderData: InvoiceOrderData,
  template: InvoiceTemplateConfig,
  pageNum: number,
  totalPages: number,
  logoDataUrl: string | null
): number {
  const pageWidth = doc.internal.pageSize.getWidth();
  const margin = 10;
  const contentWidth = pageWidth - margin * 2;
  const dist = orderData.distributor;
  const logoPosition = template.logoPosition;
  const showLogo = template.showLogo;
  const showDistributorDetails = template.showDistributorDetails;
  const showPageOf = template.showPageOf;
  const showHeaderMessage = template.showHeaderMessage;
  const headerMessageFirstPage = template.headerMessageFirstPage || '';

  // Layout: "left" = 20% logo | 35% distributor | 45% tables. "center" (beside distributor) = 35% distributor (left) | 20% logo | 45% tables.
  const logoColWidth = contentWidth * 0.2;
  const distColWidth = contentWidth * 0.35;
  // Logo width = 85% of the 20% logo column width
  const logoW = logoColWidth * 0.70;
  const logoH = 24; 

  let distStartX: number;
  let logoStartX: number;
  let rightStartX: number;
  let rightTableWidth: number;
  if (logoPosition === 'center') {
    // Beside distributor: first 35% distributor (left), then 20% logo, then 45% tables
    distStartX = margin;
    logoStartX = margin + distColWidth + 4;
    rightStartX = margin + distColWidth + logoColWidth + 8;
    rightTableWidth = pageWidth - margin - rightStartX;
  } else {
    // Left or right: 20% logo column | 35% distributor | 45% tables
    logoStartX = margin;
    distStartX = margin + logoColWidth + 4;
    rightStartX = margin + logoColWidth + distColWidth + 8;
    rightTableWidth = pageWidth - margin - rightStartX;
  }

  let headerStartY = 6;
  if (showPageOf) {
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(80, 80, 80);
    doc.text(`Page ${pageNum} of ${totalPages}`, pageWidth - margin, 6, {
      align: 'right',
    });
    headerStartY = 10;
  }

  let leftBottom = headerStartY;
  // Logo in left 20% only when position is 'left'
  if (showLogo && logoDataUrl && logoPosition === 'left') {
    try {
      doc.addImage(logoDataUrl, 'PNG', logoStartX, headerStartY, logoW, logoH);
      leftBottom = headerStartY + logoH + 2;
    } catch {
      leftBottom = headerStartY + 4;
    }
  }

  // Distributor block (35%): INVOICE title + distributor details at distStartX
  let centerY = headerStartY;
  doc.setFontSize(10);
  doc.setFont('helvetica', 'normal');
  doc.text('INVOICE', distStartX, centerY);
  centerY += 6;
  if (showDistributorDetails) {
    doc.setFontSize(9);
    doc.setFont('helvetica', 'normal');
    doc.text(dist.name, distStartX, centerY);
    centerY += 5;
    doc.setFontSize(7);
    if (dist.address) {
      const addrLines = dist.address.split(', ');
      addrLines.forEach((line: string) => {
        doc.text(line.trim(), distStartX, centerY);
        centerY += 4;
      });
    }
    if (dist.orderLine) {
      doc.text(`Order Line: ${dist.orderLine}`, distStartX, centerY);
      centerY += 4;
    }
    if (dist.phoneFax) {
      doc.text(`Phone/Fax: ${dist.phoneFax}`, distStartX, centerY);
      centerY += 4;
    }
    if (dist.whatsapp) {
      doc.text(`Whatsapp #: ${dist.whatsapp}`, distStartX, centerY);
      centerY += 4;
    }
  }

  // When "beside distributor": logo in the 20% column to the right of distributor block
  if (logoPosition === 'center' && showLogo && logoDataUrl) {
    try {
      doc.addImage(logoDataUrl, 'PNG', logoStartX, headerStartY, logoW, logoH);
      leftBottom = Math.max(leftBottom, headerStartY + logoH + 2);
    } catch {
      // ignore
    }
  }
  if (logoPosition === 'center') {
    leftBottom = Math.max(leftBottom, centerY);
  }

  // Right 45%: logo when position is 'right', then invoice info tables
  let tablesStartY = headerStartY;
  if (logoPosition === 'right' && showLogo && logoDataUrl) {
    try {
      const logoRightX = pageWidth - margin - logoW;
      doc.addImage(logoDataUrl, 'PNG', logoRightX, headerStartY, logoW, logoH);
      tablesStartY = headerStartY + logoH + 2;
    } catch {
      // ignore
    }
  }
  const tablesBottom = drawHeaderTables(doc, orderData, template, rightStartX, tablesStartY, rightTableWidth, pageWidth, margin);
  const headerBlockBottom = Math.max(leftBottom, centerY, tablesBottom) + 4;

  // Header message above Bill To / Ship To: 100% width, max 3 lines
  let billShipStartY = headerBlockBottom;
  if (showHeaderMessage && headerMessageFirstPage && pageNum === 1) {
    doc.setFontSize(7);
    doc.setFont('helvetica', 'normal');
    doc.setTextColor(0, 0, 0);
    const plainHeaderMsg = stripHtmlAndTruncate(headerMessageFirstPage, 750);
    const headerMsgMaxWidth = contentWidth - 2;
    const headerMsgLines: string[] = [];
    plainHeaderMsg.split(/\n/).forEach((para) => {
      const wrapped = wrapFooterMessage(doc, para.trim(), headerMsgMaxWidth, 3 - headerMsgLines.length);
      wrapped.forEach((l) => {
        if (headerMsgLines.length < 3) headerMsgLines.push(l);
      });
    });
    headerMsgLines.slice(0, 3).forEach((line) => {
      doc.text(line, margin, billShipStartY);
      billShipStartY += 3.5;
    });
    billShipStartY += 2;
  }

  // BILL TO / SHIP TO (same customer)
  const billShipBottom = drawBillToShipTo(doc, orderData, template, billShipStartY, margin, pageWidth, margin);

  const headerBottom = billShipBottom + 4;
  doc.setDrawColor(0, 0, 0);
  doc.setLineWidth(0.3);
  doc.line(margin, headerBottom + 2, pageWidth - margin, headerBottom + 2);
  return headerBottom + 6;
}

