/** Return selected column keys in display order: default = fixed order; custom = by columnOrder (1-based). */
function getOrderedSelectedKeys(
  template: InvoiceTemplateConfig
): string[] {
  const selected = INVOICE_COLUMN_FIELDS.filter((f) => template.selectedColumns[f.key]).map((f) => f.key);
  if (template.columnPlacement !== 'custom' || !template.columnOrder || Object.keys(template.columnOrder).length === 0) {
    return selected;
  }
  return selected.sort((a, b) => (template.columnOrder![a] ?? 999) - (template.columnOrder![b] ?? 999));
}

const SUMMARY_HEADER_HEIGHT_MM = 28;
/** Height reserved for "Report generated by Woopsa" line on last page only. */
const WOOPSA_FOOTER_HEIGHT_MM = 10;
/** Bottom margin on non-last pages (no footer/Woopsa on these pages). */
const NON_LAST_PAGE_BOTTOM_MM = 10;
/** Reserved at bottom on last page: footer block (25% summary + 75% msg) + category summary + Woopsa line. */
const LAST_PAGE_FOOTER_BLOCK_MM = 48;
const LAST_PAGE_CATEGORY_SUMMARY_MM = 28;
/** Minimal gap from page bottom so "Report generated by Woopsa" sits at bottom. */
const WOOPSA_LINE_BOTTOM_MM = 2;
/** Bottom margin so last page has room: QTY Category table + gap + footer block + Woopsa line. */
function getTableBottomMarginMM(template: InvoiceTemplateConfig): number {
  const footerAndWoopsa = LAST_PAGE_FOOTER_BLOCK_MM + 1 + WOOPSA_LINE_BOTTOM_MM; // 1mm gap between footer block and Woopsa line
  const withCategorySummary = LAST_PAGE_CATEGORY_SUMMARY_MM + GAP_CATEGORY_TO_FOOTER_MM + footerAndWoopsa;
  return Math.max(withCategorySummary, template.showReportGeneratedByWoopsa ? WOOPSA_FOOTER_HEIGHT_MM : 6);
}

const ROW_HEIGHT_EST_MM = 5;
const GROUP_HEADER_EST_MM = 8;
const SUBTOTAL_ROW_EST_MM = 5;

/** Estimate total page count when using big bottom margin on last page only (for per-page margin). */
function estimateTotalPages(
  grouped: Array<{ key: string; label?: string; items: InvoiceLineItem[] }>,
  template: InvoiceTemplateConfig,
  headerHeight: number,
  tableMarginTopNewPages: number,
  pageHeight: number,
  tableBottomMarginMM: number
): number {
  let pages = 1;
  let y = headerHeight + 2;
  const minYLast = pageHeight - tableBottomMarginMM;
  const showGroupSubtotal =
    template.groupBy === 'alphabetSalesCategory' || template.groupBy === 'sequence';
  const hasGroupHeader =
    (template.groupBy === 'alphabetSalesCategory' && template.showGroupHeader) ||
    (template.groupBy === 'sequence' && template.showGroupHeader);

  grouped.forEach((group, groupIdx) => {
    if (groupIdx > 0) y += 4;
    if (hasGroupHeader) {
      if (y + GROUP_HEADER_EST_MM > minYLast) {
        pages += 1;
        y = tableMarginTopNewPages + 2;
      }
      y += GROUP_HEADER_EST_MM;
    }
    const rowsH = group.items.length * ROW_HEIGHT_EST_MM;
    if (y + rowsH > minYLast) {
      let remaining = rowsH;
      while (remaining > 0) {
        const space = minYLast - y;
        if (space <= 0) {
          pages += 1;
          y = tableMarginTopNewPages + 2;
          continue;
        }
        const rowsFit = Math.floor(space / ROW_HEIGHT_EST_MM);
        remaining -= rowsFit * ROW_HEIGHT_EST_MM;
        if (remaining > 0) {
          pages += 1;
          y = tableMarginTopNewPages + 2;
        } else {
          y += rowsFit * ROW_HEIGHT_EST_MM;
        }
      }
    } else {
      y += rowsH;
    }
    if (showGroupSubtotal) {
      if (y + SUBTOTAL_ROW_EST_MM > minYLast) {
        pages += 1;
        y = tableMarginTopNewPages + 2;
      }
      y += SUBTOTAL_ROW_EST_MM + 4;
    } else {
      y += 4;
    }
  });
  return pages;
}
